// Import the supplied vector directly; rotate its diagonal axis 45° to point right.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const native = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const svg = await readFile(join(native, "Assets/jack-source.svg"), "utf8");
const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map(match => match[1]);
if (paths.length !== 5) throw new Error("Expected the five paths from the supplied jack SVG.");
const n = value => Number(value.toFixed(8));
const point = ([x, y]) => `CGPoint(x: ${n(x)}, y: ${n(y)})`;
const lines = [];
const bounds = [];

for (const data of paths) {
  const tokens = data.match(/[A-Za-z]|[-+]?(?:\d*\.)?\d+(?:[eE][-+]?\d+)?/g);
  let index = 0, current = [0, 0], start;
  const number = () => Number(tokens[index++]);
  const pair = () => {
    const p = [number(), number()];
    bounds.push([(p[0] - p[1]) / Math.SQRT2, (p[0] + p[1]) / Math.SQRT2]);
    return p;
  };
  while (index < tokens.length) {
    const command = tokens[index++];
    if (command === "Z") {
      lines.push("        path.closeSubpath()");
      current = start;
      continue;
    }
    if (command === "A") {
      const rx = number(), ry = number(), rotation = number(), large = number(), sweep = number();
      const end = pair();
      if (rx !== ry || rotation !== 0 || large !== 0) throw new Error("Unsupported source arc.");
      const dx = (current[0] - end[0]) / 2, dy = (current[1] - end[1]) / 2;
      const distance = dx * dx + dy * dy;
      const radius = Math.max(rx, Math.sqrt(distance));
      const factor = (sweep ? 1 : -1) * Math.sqrt(Math.max(0, radius * radius / distance - 1));
      const center = [(current[0] + end[0]) / 2 + factor * dy,
        (current[1] + end[1]) / 2 - factor * dx];
      const angle = p => Math.atan2(p[1] - center[1], p[0] - center[0]);
      lines.push(`        path.addArc(center: ${point(center)}, radius: ${n(radius)}, startAngle: .radians(${n(angle(current))}), endAngle: .radians(${n(angle(end))}), clockwise: ${!sweep})`);
      current = end;
      continue;
    }
    const count = { M: 1, L: 1, Q: 2, C: 3 }[command];
    if (!count) throw new Error(`Unsupported SVG command: ${command}`);
    const points = Array.from({ length: count }, pair);
    current = points.at(-1);
    if (command === "M") {
      start = current;
      lines.push(`        path.move(to: ${point(current)})`);
    } else if (command === "L") lines.push(`        path.addLine(to: ${point(current)})`);
    else if (command === "Q") lines.push(`        path.addQuadCurve(to: ${point(current)}, control: ${point(points[0])})`);
    else lines.push(`        path.addCurve(to: ${point(current)}, control1: ${point(points[0])}, control2: ${point(points[1])})`);
  }
}

await writeFile(join(native, "Sources/KMSA/JackConnector.swift"), `// Generated by native/scripts/import-jack-svg.mjs from Assets/jack-source.svg.
import SwiftUI

struct JackConnector: Shape {
    func path(in rect: CGRect) -> Path {
        var path = Path()
${lines.join("\n")}
        let horizontal = path.applying(CGAffineTransform(rotationAngle: .pi / 4))
        let bounds = horizontal.cgPath.boundingBoxOfPath
        let scale = min(rect.width / bounds.width, rect.height / bounds.height)
        return horizontal.applying(CGAffineTransform(scaleX: scale, y: scale)
            .concatenating(CGAffineTransform(translationX: rect.midX - bounds.midX * scale,
                                            y: rect.midY - bounds.midY * scale)))
    }
}
`);
const min = [0, 1].map(axis => Math.min(...bounds.map(p => p[axis])) - 1);
const max = [0, 1].map(axis => Math.max(...bounds.map(p => p[axis])) + 1);
await writeFile(join(native, "Assets/jack-horizontal.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${min.map(n).join(" ")} ${max.map((v, i) => n(v - min[i])).join(" ")}"><g transform="rotate(45)">${paths.map(d => `<path fill="#262626" d="${d}"/>`).join("")}</g></svg>\n`);
console.log("Imported the five original SVG paths, rotated horizontally without stretching.");
