// Trace the supplied reference, rotate its geometry upright, and emit a native vector.
// Run manually when the source changes; rebuilding the app needs no image tools.
import { spawnSync } from "node:child_process";
import { readFile, writeFile, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const native = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const work = await mkdtemp(join(tmpdir(), "kmsa-jack-"));
function run(command, args) {
  const result = spawnSync(command, args, { encoding: "utf8" });
  if (result.status !== 0) throw result.error ?? new Error(result.stderr);
}
try {
  run("magick", [join(native, "Assets/jack-reference.png"), "-threshold", "50%", join(work, "mask.pbm")]);
  run("potrace", [join(work, "mask.pbm"), "--svg", "--tight", "--flat", "--color", "#000000",
    "--output", join(work, "trace.svg")]);
  const svg = await readFile(join(work, "trace.svg"), "utf8");
  const data = svg.match(/<path d="([^"]+)"/)[1];
  const tokens = data.match(/[MmLlCcZz]|[-+]?(?:\d*\.)?\d+(?:[eE][-+]?\d+)?/g);
  const segments = [];
  let i = 0, command, point = [0, 0], start;
  const rotate = ([x, y]) => [(x - y) / Math.SQRT2 / 10, -(x + y) / Math.SQRT2 / 10];
  while (i < tokens.length) {
    if (/^[a-z]$/i.test(tokens[i])) command = tokens[i++];
    const type = command.toUpperCase();
    if (type === "Z") { segments.push({ type }); point = start; continue; }
    const count = type === "C" ? 3 : 1;
    const points = [];
    for (let j = 0; j < count; j++) {
      let next = [Number(tokens[i++]), Number(tokens[i++])];
      if (command === command.toLowerCase()) next = next.map((value, axis) => value + point[axis]);
      points.push(next);
    }
    point = points.at(-1);
    if (type === "M") { start = point; command = command === "m" ? "l" : "L"; }
    segments.push({ type, points: points.map(rotate) });
  }
  // Sample the cubic geometry for tight visible bounds (including its extrema).
  const samples = [];
  let previous;
  for (const segment of segments) {
    if (segment.type === "C") {
      const [b, c, d] = segment.points;
      for (let step = 0; step <= 100; step++) {
        const t = step / 100, u = 1 - t;
        samples.push([0, 1].map(axis => u ** 3 * previous[axis] + 3 * u ** 2 * t * b[axis]
          + 3 * u * t ** 2 * c[axis] + t ** 3 * d[axis]));
      }
    } else if (segment.points) samples.push(...segment.points);
    if (segment.points) previous = segment.points.at(-1);
  }
  const min = [0, 1].map(axis => Math.min(...samples.map(p => p[axis])));
  const max = [0, 1].map(axis => Math.max(...samples.map(p => p[axis])));
  const [width, height] = max.map((v, axis) => v - min[axis]);
  const number = n => Number(n.toFixed(5));
  for (const segment of segments) {
    if (segment.points) segment.points = segment.points.map(p => p.map((v, axis) => number(v - min[axis])));
  }
  const upright = segments.map(s => s.type + (s.points?.flat().join(" ") ?? "")).join(" ");
  await writeFile(join(native, "Assets/jack-upright.svg"),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${number(width)} ${number(height)}"><path fill="#000000" d="${upright}"/></svg>\n`);
  const cg = p => `CGPoint(x: ${p[0]}, y: ${p[1]})`;
  const code = segments.map(s => {
    if (s.type === "Z") return "        path.closeSubpath()";
    if (s.type === "M") return `        path.move(to: ${cg(s.points[0])})`;
    if (s.type === "L") return `        path.addLine(to: ${cg(s.points[0])})`;
    return `        path.addCurve(to: ${cg(s.points[2])}, control1: ${cg(s.points[0])}, control2: ${cg(s.points[1])})`;
  }).join("\n");
  await writeFile(join(native, "Sources/KMSA/JackConnector.swift"), `// Generated by native/scripts/vectorize-jack.mjs from the supplied reference.\nimport SwiftUI\n\nstruct JackConnector: Shape {\n    func path(in rect: CGRect) -> Path {\n        var path = Path()\n${code}\n        let scale = min(rect.width / ${number(width)}, rect.height / ${number(height)})\n        return path.applying(CGAffineTransform(scaleX: scale, y: scale)\n            .concatenating(CGAffineTransform(translationX: rect.midX - ${number(width)} * scale / 2,\n                                            y: rect.midY - ${number(height)} * scale / 2)))\n    }\n}\n`);
  console.log(`Traced the source silhouette and rotated 45 degrees upright: ${number(width)} × ${number(height)}. No stretching.`);
} finally {
  await rm(work, { recursive: true, force: true });
}
